#!/usr/bin/env python3
"""Generate the ESM server module from the canonical offline rule body."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=(root/'app/assets/core.js').read_text()
body=source[source.index(" 'use strict';"):source.rfind('\n});')]
(root/'server/functions/navrang-gate/core.mjs').write_text('// Generated by tools/sync-server-core.py; edit app/assets/core.js.\nconst Core=(()=>{\n'+body+'\n})();\nexport default Core;\n')
